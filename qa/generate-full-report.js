const PDFDocument = require("pdfkit");
const fs = require("fs");
const path = require("path");

async function generateFullReport(allResults) {
    const doc = new PDFDocument();
    const reportPath = path.join(__dirname, "reports", "complete-e2e-test-report.pdf");
    
    if (!fs.existsSync(path.join(__dirname, "reports"))) {
        fs.mkdirSync(path.join(__dirname, "reports"));
    }

    const output = fs.createWriteStream(reportPath);
    doc.pipe(output);

    // Title
    doc.fontSize(25).text("Malstro Complete E2E Test Report", { align: "center" });
    doc.moveDown();
    doc.fontSize(12).text(`Date: ${new Date().toLocaleString()}`);
    doc.text("Generated by: GitHub Copilot Automation");
    doc.moveDown();
    doc.moveTo(50, doc.y).lineTo(550, doc.y).stroke();
    doc.moveDown();

    // Overall Summary
    doc.fontSize(18).text("Overall Summary", { underline: true });
    doc.moveDown(0.5);

    let totalTests = 0;
    let totalPassed = 0;
    Object.values(allResults).forEach(suite => {
        totalTests += suite.length;
        totalPassed += suite.filter(r => r.status === "passed").length;
    });

    doc.fontSize(12).text(`Total Test Cases: ${totalTests}`, { indent: 20 });
    doc.fontSize(12).text(`Passed: ${totalPassed}`, { indent: 20, color: "green" });
    doc.fillColor("black");
    doc.fontSize(12).text(`Failed: ${totalTests - totalPassed}`, { indent: 20, color: (totalTests - totalPassed) > 0 ? "red" : "black" });
    doc.fillColor("black");
    doc.moveDown();

    // Results by Section
    for (const [suiteTitle, results] of Object.entries(allResults)) {
        doc.addPage();
        doc.fontSize(20).text(suiteTitle, { underline: true });
        doc.moveDown();

        results.forEach((result, index) => {
            doc.fontSize(14).text(`${index + 1}. ${result.title}`, { bold: true });
            doc.fontSize(12).text(`Status: ${result.status.toUpperCase()}`, { 
                indent: 20, 
                color: result.status === "passed" ? "green" : "red" 
            });
            doc.fillColor("black");
            if (result.error) {
                doc.fontSize(10).text(`Error: ${result.error}`, { indent: 20, color: "red" });
                doc.fillColor("black");
            }
            doc.moveDown(0.5);
        });
    }

    doc.end();
    console.log(`Unified report generated at: ${reportPath}`);
}

function traverseSuites(suites, resultsMap = {}) {
    suites.forEach(suite => {
        if (suite.specs && suite.specs.length > 0) {
            const suiteTitle = suite.title || "Main Suite";
            if (!resultsMap[suiteTitle]) resultsMap[suiteTitle] = [];
            
            suite.specs.forEach(spec => {
                spec.tests.forEach(test => {
                    resultsMap[suiteTitle].push({
                        title: spec.title,
                        status: test.results[0]?.status || "unknown",
                        error: test.results[0]?.error?.message
                    });
                });
            });
        }
        if (suite.suites) {
            traverseSuites(suite.suites, resultsMap);
        }
    });
    return resultsMap;
}

const playwrightJsonPath = path.join(__dirname, "..", "app", "playwright-report", "full_results.json");
if (fs.existsSync(playwrightJsonPath)) {
    let content = fs.readFileSync(playwrightJsonPath, "utf8");
    if (content.charCodeAt(0) === 0xFEFF) content = content.slice(1);
    content = content.replace(/\u0000/g, ""); 
    
    try {
        const data = JSON.parse(content);
        const allResults = traverseSuites(data.suites);
        generateFullReport(allResults);
    } catch (err) {
        console.error("Error parsing JSON:", err.message);
    }
} else {
    console.error("Playwright full_results.json not found.");
}